import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';
import { describe, expect, it } from 'vitest';
import { antigravityAdapter } from '../../../scripts/agent-adapter/adapters/antigravity';
import { claudeAdapter, renderClaudeSubagents } from '../../../scripts/agent-adapter/adapters/claude';
import { GENERATED_MARKER } from '../../../scripts/agent-adapter/core/adapter';
import { loadSubagents } from '../../../scripts/agent-adapter/core/load';
import { AgentConfig, Subagent } from '../../../scripts/agent-adapter/core/model';
import { sync } from '../../../scripts/agent-adapter/core/sync';
import { writeConfig } from '../../../scripts/agent-adapter/core/write';

describe('Subagents Adapter, Loader & Engine', () => {
  describe('(a) Claude Subagents Renderer', () => {
    it('renders subagent markdown correctly with all fields, deduplicated tools, and x-claude', () => {
      const sample: Subagent = {
        name: 'verifier',
        description: 'Chạy kiểm tra CI',
        tools: ['read', 'shell', 'read'],
        model: 'fast',
        readOnly: true,
        skills: ['verify-ci'],
        prompt: 'Prompt content here.',
        'x-claude': {
          maxTurns: 15,
          verbose: true,
          mode: 'strict',
        },
      };

      const outputs = renderClaudeSubagents([sample]);
      expect(outputs).toHaveLength(1);
      const out = outputs[0];
      expect(out.kind).toBe('own');
      expect(out.path).toBe('.claude/agents/verifier.md');

      if (out.kind === 'own') {
        const content = out.content;
        const expectedLines = [
          '---',
          'name: verifier',
          'description: "Chạy kiểm tra CI"',
          'tools: Read, Grep, Glob, Bash',
          'disallowedTools: Edit, Write',
          'model: haiku',
          'maxTurns: 15',
          'verbose: true',
          'mode: "strict"',
          'skills:',
          '  - verify-ci',
          '---',
          '<!-- generated by yarn agents:sync — sửa ở .agents/adapter/subagents/verifier/ -->',
          '',
          'Prompt content here.',
          '',
          '',
        ];
        expect(content).toBe(expectedLines.join('\n'));
      }
    });

    it('renders non-scalar x-claude values as JSON (valid YAML flow style), never [object Object]', () => {
      const sample: Subagent = {
        name: 'nested',
        description: 'desc',
        tools: ['read'],
        model: 'inherit',
        readOnly: false,
        skills: [],
        prompt: 'p',
        'x-claude': {
          hooks: { PreToolUse: [{ matcher: 'Bash' }] },
          list: [1, 2],
          nothing: null,
        },
      };

      const out = renderClaudeSubagents([sample])[0];
      expect(out.kind).toBe('own');
      if (out.kind === 'own') {
        expect(out.content).toContain('hooks: {"PreToolUse":[{"matcher":"Bash"}]}');
        expect(out.content).toContain('list: [1,2]');
        expect(out.content).toContain('nothing: null');
        expect(out.content).not.toContain('[object Object]');
      }
    });

    it('omits disallowedTools when readOnly is false, and omits skills block when empty', () => {
      const sample: Subagent = {
        name: 'builder',
        description: 'Xây dựng dự án',
        tools: ['read', 'edit', 'shell'],
        model: 'strong',
        readOnly: false,
        skills: [],
        prompt: 'Build the project.',
      };

      const outputs = renderClaudeSubagents([sample]);
      const out = outputs[0];
      expect(out.kind).toBe('own');
      if (out.kind === 'own') {
        const content = out.content;

        expect(content).not.toContain('disallowedTools');
        expect(content).not.toContain('skills:');
        expect(content).toContain('model: opus');
        expect(content).toContain('tools: Read, Grep, Glob, Edit, Write, Bash');
      }
    });
  });

  describe('(b) loadSubagents validation', () => {
    let tmpDir: string;

    const setupSubagent = (
      name: string,
      agentJson: string | null,
      promptMd: string | null,
      extraSetup?: (dir: string) => void,
    ) => {
      tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'subagent-test-'));
      const subagentDir = path.join(tmpDir, '.agents', 'adapter', 'subagents', name);
      fs.mkdirSync(subagentDir, { recursive: true });

      if (agentJson !== null) {
        fs.writeFileSync(path.join(subagentDir, 'agent.json'), agentJson, 'utf-8');
      }
      if (promptMd !== null) {
        fs.writeFileSync(path.join(subagentDir, 'prompt.md'), promptMd, 'utf-8');
      }
      if (extraSetup) {
        extraSetup(tmpDir);
      }
      return tmpDir;
    };

    it('returns empty array when subagents directory does not exist', () => {
      const emptyDir = fs.mkdtempSync(path.join(os.tmpdir(), 'empty-'));
      expect(loadSubagents(emptyDir)).toEqual([]);
    });

    it('throws error when agent.json is missing', () => {
      const root = setupSubagent('verifier', null, 'prompt');
      expect(() => loadSubagents(root)).toThrow(/Thiếu file cấu hình tại .*agent\.json/);
    });

    it('throws error when prompt.md is missing', () => {
      const root = setupSubagent('verifier', '{"name":"verifier"}', null);
      expect(() => loadSubagents(root)).toThrow(/Thiếu file prompt tại .*prompt\.md/);
    });

    it('throws error when prompt.md is empty', () => {
      const root = setupSubagent('verifier', '{"name":"verifier"}', '   ');
      expect(() => loadSubagents(root)).toThrow(/Nội dung prompt tại .* không được để trống/);
    });

    it('throws error on JSON syntax error', () => {
      const root = setupSubagent('verifier', '{ invalid json }', 'prompt');
      expect(() => loadSubagents(root)).toThrow(/Lỗi cú pháp JSON tại .*agent\.json/);
    });

    it('throws error when name does not match directory name', () => {
      const root = setupSubagent(
        'verifier',
        JSON.stringify({
          name: 'different-name',
          description: 'desc',
          tools: ['read'],
          model: 'fast',
        }),
        'prompt',
      );
      expect(() => loadSubagents(root)).toThrow(/không khớp với tên thư mục "verifier"/);
    });

    it('throws error when the directory name is not a valid subagent name', () => {
      const valid = { description: 'desc', tools: ['read'], model: 'fast' };
      for (const badName of ['Bad_Name', '-leading-dash', 'has space', 'UPPER']) {
        const root = setupSubagent(badName, JSON.stringify({ name: badName, ...valid }), 'prompt');
        expect(() => loadSubagents(root)).toThrow(/Tên subagent ".*" không hợp lệ/);
      }

      const okRoot = setupSubagent('ok-name-2', JSON.stringify({ name: 'ok-name-2', ...valid }), 'prompt');
      expect(loadSubagents(okRoot).map(s => s.name)).toEqual(['ok-name-2']);
    });

    it('throws error when tools is empty or contains invalid category', () => {
      const root1 = setupSubagent(
        'v1',
        JSON.stringify({ name: 'v1', description: 'desc', tools: [], model: 'fast' }),
        'prompt',
      );
      expect(() => loadSubagents(root1)).toThrow(/Trường "tools" .* phải là danh sách không rỗng/);

      const root2 = setupSubagent(
        'v2',
        JSON.stringify({ name: 'v2', description: 'desc', tools: ['invalid_tool'], model: 'fast' }),
        'prompt',
      );
      expect(() => loadSubagents(root2)).toThrow(/Giá trị tool không hợp lệ "invalid_tool"/);
    });

    it('throws error on unknown model tier', () => {
      const root = setupSubagent(
        'v1',
        JSON.stringify({ name: 'v1', description: 'desc', tools: ['read'], model: 'ultra' }),
        'prompt',
      );
      expect(() => loadSubagents(root)).toThrow(/Giá trị model không hợp lệ "ultra"/);
    });

    it('throws error when readOnly: true but tools include edit', () => {
      const root = setupSubagent(
        'v1',
        JSON.stringify({
          name: 'v1',
          description: 'desc',
          tools: ['read', 'edit'],
          model: 'fast',
          readOnly: true,
        }),
        'prompt',
      );
      expect(() => loadSubagents(root)).toThrow(/có "readOnly: true" nhưng danh sách tools lại chứa "edit"/);
    });

    it('throws error when referenced skill does not exist in .agents/skills/', () => {
      const root = setupSubagent(
        'v1',
        JSON.stringify({
          name: 'v1',
          description: 'desc',
          tools: ['read'],
          model: 'fast',
          skills: ['non-existent-skill'],
        }),
        'prompt',
      );
      expect(() => loadSubagents(root)).toThrow(/Skill "non-existent-skill" .* không tồn tại/);
    });
  });

  describe('(c) Antigravity subagents support', () => {
    it('declares unsupported for subagents and renders no outputs', () => {
      const subagentHandler = antigravityAdapter.render.subagents;
      expect('unsupported' in subagentHandler).toBe(true);
      if ('unsupported' in subagentHandler) {
        expect(subagentHandler.unsupported).toContain('Antigravity chỉ nạp subagent từ plugin');
      }
    });
  });

  describe('(d) writeConfig managedDirs cleanup with GENERATED_MARKER', () => {
    it('deletes stale generated .md files in managedDirs, preserves handwritten ones, and reports stale in --check', () => {
      const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'managed-dirs-test-'));
      const claudeAgentsDir = path.join(tmpDir, '.claude', 'agents');
      fs.mkdirSync(claudeAgentsDir, { recursive: true });

      // File sinh cũ (stale) có GENERATED_MARKER
      const staleFile = path.join(claudeAgentsDir, 'old-agent.md');
      fs.writeFileSync(
        staleFile,
        `---\nname: old\n---\n${GENERATED_MARKER} — sửa ở .agents/adapter/subagents/old/ -->\n\nOld prompt`,
        'utf-8',
      );

      // File viết tay không có GENERATED_MARKER
      const manualFile = path.join(claudeAgentsDir, 'manual-agent.md');
      fs.writeFileSync(manualFile, '---\nname: manual\n---\n\nManual prompt without marker', 'utf-8');

      // Check mode
      const checkRes = writeConfig(tmpDir, [], [claudeAdapter], { check: true });
      expect(checkRes.removed).toContain('.claude/agents/old-agent.md');
      expect(checkRes.removed).not.toContain('.claude/agents/manual-agent.md');
      expect(fs.existsSync(staleFile)).toBe(true);
      expect(fs.existsSync(manualFile)).toBe(true);

      // Write mode
      const writeRes = writeConfig(tmpDir, [], [claudeAdapter]);
      expect(writeRes.removed).toContain('.claude/agents/old-agent.md');
      expect(fs.existsSync(staleFile)).toBe(false);
      expect(fs.existsSync(manualFile)).toBe(true);
    });
  });

  describe('(d2) managedDirs cleanup only trusts the marker in the header', () => {
    it('keeps handwritten .md files that merely mention the marker text or have it far below the header', () => {
      const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'managed-marker-test-'));
      const claudeAgentsDir = path.join(tmpDir, '.claude', 'agents');
      fs.mkdirSync(claudeAgentsDir, { recursive: true });

      const mentionFile = path.join(claudeAgentsDir, 'mentions-marker.md');
      fs.writeFileSync(
        mentionFile,
        `---\nname: mention\n---\nFile này nhắc tới chuỗi \`${GENERATED_MARKER}\` trong thân bài.\n`,
        'utf-8',
      );

      const farFile = path.join(claudeAgentsDir, 'marker-far-below.md');
      const filler = Array.from({ length: 60 }, (_, i) => `dòng ${i}`).join('\n');
      fs.writeFileSync(farFile, `---\nname: far\n---\n${filler}\n${GENERATED_MARKER} -->\n`, 'utf-8');

      const res = writeConfig(tmpDir, [], [claudeAdapter]);
      expect(res.removed).toEqual([]);
      expect(fs.existsSync(mentionFile)).toBe(true);
      expect(fs.existsSync(farFile)).toBe(true);
    });
  });

  describe('(e) Dynamic kinds in sync.ts', () => {
    it('processes all kinds present in config dynamically without hardcoded list', () => {
      const customConfig = {
        mcp: [],
        skills: [],
        subagents: [],
        hooks: [],
      } as AgentConfig;

      const { outputs, notes } = sync(customConfig, [claudeAdapter, antigravityAdapter]);
      expect(Array.isArray(outputs)).toBe(true);
      expect(notes).toContain(
        'antigravity: subagents unsupported (Antigravity chỉ nạp subagent từ plugin hoặc define_subagent lúc runtime, xem PLAN-agent-adapter.md mục 14)',
      );
    });
  });
});
