const fs = require('fs');
const path = require('path');

const GENERATED_MARKER = '<!-- generated by yarn agents:sync';

const STATIC_GENERATED_FILES = [
  '.mcp.json',
  '.agents/mcp_config.json',
  '.agents/hooks.json',
];

function isGeneratedFile(repoRoot, relPath) {
  const normalized = path.posix.normalize(relPath.replace(/\\/g, '/')).replace(/^\.\//, '');
  const lower = normalized.toLowerCase();

  if (STATIC_GENERATED_FILES.includes(lower)) {
    return true;
  }

  if (lower.startsWith('.claude/agents/') && lower.endsWith('.md')) {
    const parts = normalized.split('/');
    if (parts.length === 3) {
      const fullPath = path.resolve(repoRoot, normalized);
      if (fs.existsSync(fullPath)) {
        try {
          const content = fs.readFileSync(fullPath, 'utf-8');
          const lines = content.split('\n').slice(0, 40);
          for (const line of lines) {
            if (line.trim().startsWith(GENERATED_MARKER)) {
              return true;
            }
          }
        } catch {
          return false;
        }
      }
    }
  }

  return false;
}

module.exports = {
  GENERATED_MARKER,
  STATIC_GENERATED_FILES,
  isGeneratedFile,
};
