import { AgentAdapter, GeneratedOutput } from '../../core/adapter';
import { Hook, McpServer, SkillLink, Subagent } from '../../core/model';
import { CLAUDE_MODEL_MAP, CLAUDE_TOOL_MAP } from './maps';

export function renderClaudeHooks(hooks: Hook[]): GeneratedOutput[] {
  const targetHooks = hooks.filter(h => !h.targets || h.targets.includes('claude'));
  if (targetHooks.length === 0) {
    return [];
  }

  const renderedHooks: Record<
    string,
    Array<{ matcher?: string; hooks: Array<{ type: 'command'; command: string; timeout?: number }> }>
  > = {};

  for (const h of targetHooks) {
    const toolNames: string[] = [];
    if (h.tools && h.tools.length > 0) {
      for (const cat of h.tools) {
        for (const t of CLAUDE_TOOL_MAP[cat] || []) {
          if (!toolNames.includes(t)) {
            toolNames.push(t);
          }
        }
      }
    }

    const command = `node "\${CLAUDE_PROJECT_DIR}/scripts/agent-adapter/hook-runner.js" ${h.id} --agent=claude`;
    const action: { type: 'command'; command: string; timeout?: number } = {
      type: 'command',
      command,
    };
    if (h.timeout !== undefined) {
      action.timeout = h.timeout;
    }

    const entry: { matcher?: string; hooks: Array<{ type: 'command'; command: string; timeout?: number }> } = {
      hooks: [action],
    };
    if (toolNames.length > 0) {
      entry.matcher = toolNames.join('|');
    }

    if (!renderedHooks[h.event]) {
      renderedHooks[h.event] = [];
    }
    renderedHooks[h.event].push(entry);
  }

  return [
    {
      kind: 'merge-key',
      path: '.claude/settings.json',
      key: 'hooks',
      value: renderedHooks,
    },
  ];
}

export function renderClaudeMcp(servers: McpServer[]): GeneratedOutput[] {
  const mcpServers: Record<string, unknown> = {};

  for (const s of servers) {
    const extra = (s['x-claude'] as Record<string, unknown> | undefined) || {};
    if (s.transport === 'stdio') {
      mcpServers[s.id] = {
        type: 'stdio',
        command: s.command,
        args: s.args,
        env: s.env,
        ...extra,
      };
    } else {
      mcpServers[s.id] = {
        type: 'http',
        url: s.url,
        headers: s.headers,
        ...extra,
      };
    }
  }

  const content = JSON.stringify({ mcpServers }, null, 2) + '\n';
  return [
    {
      kind: 'own',
      path: '.mcp.json',
      content,
    },
  ];
}

export function renderClaudeSkills(skills: SkillLink[]): GeneratedOutput[] {
  return skills
    .filter(skill => !skill.excludeFor?.includes('claude'))
    .map(
      (skill): GeneratedOutput => ({
        kind: 'symlink',
        path: `.claude/skills/${skill.name}`,
        target: `../../.agents/skills/${skill.name}`,
      }),
    );
}

export function renderClaudeSubagents(subagents: Subagent[]): GeneratedOutput[] {
  return subagents.map(subagent => {
    const lines: string[] = ['---'];
    lines.push(`name: ${subagent.name}`);
    lines.push(`description: ${JSON.stringify(subagent.description)}`);

    const toolsList: string[] = [];
    for (const cat of subagent.tools) {
      for (const toolName of CLAUDE_TOOL_MAP[cat]) {
        if (!toolsList.includes(toolName)) {
          toolsList.push(toolName);
        }
      }
    }
    lines.push(`tools: ${toolsList.join(', ')}`);

    if (subagent.readOnly) {
      lines.push('disallowedTools: Edit, Write');
    }

    lines.push(`model: ${CLAUDE_MODEL_MAP[subagent.model]}`);

    const extra = (subagent['x-claude'] as Record<string, unknown> | undefined) || {};
    for (const [k, v] of Object.entries(extra)) {
      if (v === undefined) {
        continue;
      }
      const rendered = typeof v === 'number' || typeof v === 'boolean' ? String(v) : JSON.stringify(v);
      lines.push(`${k}: ${rendered}`);
    }

    if (subagent.skills.length > 0) {
      lines.push('skills:');
      for (const skill of subagent.skills) {
        lines.push(`  - ${skill}`);
      }
    }

    lines.push('---');
    lines.push(`<!-- generated by yarn agents:sync — sửa ở .agents/adapter/subagents/${subagent.name}/ -->`);
    lines.push('');
    lines.push(subagent.prompt.trim());
    lines.push('');

    const content = lines.join('\n') + '\n';
    return {
      kind: 'own',
      path: `.claude/agents/${subagent.name}.md`,
      content,
    };
  });
}

export const claudeAdapter: AgentAdapter = {
  id: 'claude',
  render: {
    mcp: renderClaudeMcp,
    skills: renderClaudeSkills,
    subagents: renderClaudeSubagents,
    hooks: renderClaudeHooks,
  },
  managedDirs: ['.claude/skills', '.claude/agents'],
};
